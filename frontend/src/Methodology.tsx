import { Users, Layers, ClipboardCheck } from "lucide-react";
import { Heading } from "./components";
import type { Catalog } from "./types";

const TONE: Record<string, string> = { согласуется: "ok", устарело: "old" };
const STATUS: Record<string, string> = {
  согласуется: "Согласуется",
  ориентир: "Ориентир",
  устарело: "Нужно обновить",
};

export default function Methodology({ catalog }: { catalog?: Catalog | null }) {
  const sources = catalog?.sources;
  return (
    <>
      <Heading
        title="Как читать исследование"
        description="Синтетические ответы помогают подготовить живую проверку. Качество прогноза требует независимых данных."
      />
      <div className="method-process">
        <div>
          <Users size={26} />
          <h2>Профили</h2>
          <p>
            Популяция составлена из семи экспертных сегментов. Доли задаёт
            исследователь; часть атрибутов сверена с открытыми данными, но
            калибровки выборки пока нет.
          </p>
        </div>
        <div>
          <Layers size={26} />
          <h2>Симуляция</h2>
          <p>
            Одни и те же профили оценивают все предложения. Демо использует
            эвристику, LLM играет персонажей и объясняет решения.
          </p>
        </div>
        <div>
          <ClipboardCheck size={26} />
          <h2>Живая проверка</h2>
          <p>
            Опрос позволяет сопоставить доли и ранжирование. Сам факт загрузки
            CSV не подтверждает подлинность ответов или точность модели.
          </p>
        </div>
      </div>
      <section className="method-section">
        <h2>Что означают числа</h2>
        <p>
          Конверсия в отчёте — заявленная готовность синтетических персонажей.
          Она не равна фактическому оформлению продукта людьми. Ошибки модели
          отделены от отказов и исключены из знаменателя.
        </p>
        <p>
          95% интервалы Wilson описывают ответы внутри симуляции и не оценивают
          точность прогноза реального спроса. Ничьи сохраняются; цвет лидера в
          матрице не означает статистической значимости.
        </p>
      </section>
      <section className="method-section">
        <h2>Встроенные проверки качества</h2>
        <p>
          <strong>Простой подход.</strong> Вместе с симуляцией выполняется один
          запрос к той же модели без персонажей: «какая доля аудитории
          согласится». Если двойники дают то же ранжирование, персонажи не
          добавляют информации; после живого опроса ошибки обоих подходов
          сравниваются на одних данных. В демо вместо запроса используется
          правило без профилей.
        </p>
        <p>
          <strong>Устойчивость лидера.</strong> Доля повторных выборок ответов
          (бета-распределение по сохранённым количествам), в которых лидер
          остаётся первым. Это разброс внутри симуляции, а не точность. Для
          проверки на другой популяции используйте повторы с соседними seed
          (CLI: <code>--repeats</code>).
        </p>
        <p>
          <strong>Однородность.</strong> Для LLM сохраняется средняя и разброс
          заявленной вероятности. Разброс меньше 5 п.п. означает, что модель
          отвечает одинаково независимо от профиля.
        </p>
        <p>
          <strong>Режим SSR.</strong> Если задать DVOINIK_ELICITATION=ssr,
          двойник отвечает фразой без чисел, а готовность считается по смысловой
          близости ответа к пяти эталонным ответам шкалы 1–5. В исследовании
          PyMC Labs и Colgate на 57 опросах такой способ дал распределения
          намного ближе к человеческим, чем прямой вопрос с оценкой: модели
          перестают сбиваться к середине шкалы.
        </p>
        <p>
          <strong>Гипотезы изменений.</strong> Частые причины отказа от лидера
          группируются по рычагу: цена, канал, доверие, понятность и другие. Для
          рычага правило готовит черновик нового текста, в LLM-режиме его можно
          переписать моделью. Потолок эффекта — прирост, если причина исчезнет
          полностью; реальный эффект меньше. Каждую гипотезу можно сразу
          проверить A/B-запуском «лидер против гипотезы» на тех же сегментах.
        </p>
        <p>
          <strong>План живой проверки.</strong> Размер выборки рассчитывается
          для двустороннего теста двух долей (α = 0,05, мощность 80%) по долям
          симуляции. Это ориентир: настоящие доли могут отличаться.
        </p>
      </section>
      {sources ? (
        <section className="method-section">
          <h2>С чем сверены сегменты</h2>
          <p>
            Опорные открытые цифры показывают, на что опираются профили и что
            остаётся допущением. Это не калибровка: доли аудитории по-прежнему
            задаёт исследователь.
          </p>
          <div className="source-list">
            {Object.entries(sources.segments).map(([sid, items]) => (
              <div key={sid} className="source-group">
                <h3>{catalog?.segments[sid]?.name ?? sid}</h3>
                <ul>
                  {items.map((item) => (
                    <li key={item.fact}>
                      <span
                        className={`source-status ${TONE[item.status] ?? ""}`}
                      >
                        {STATUS[item.status] ?? item.status}
                      </span>
                      <strong>{item.fact}</strong>
                      <span>{item.use}</span>
                      <a href={item.url} target="_blank" rel="noreferrer">
                        {item.source}, {item.date}
                      </a>
                    </li>
                  ))}
                </ul>
              </div>
            ))}
          </div>
          <p className="help">{sources.gaps}</p>
          {catalog?.risks && (
            <p>
              <strong>Риск искажений.</strong> В мегаисследовании Columbia
              двойники точнее описывали людей с высоким доходом и образованием.
              Сегменты с низким доходом —{" "}
              {Object.keys(catalog.risks.segments)
                .map((sid) => catalog.segments[sid]?.name ?? sid)
                .join(", ")}{" "}
              — отмечены в отчёте и в паспорте исследования: их стоит проверять
              на людях в первую очередь.{" "}
              <a href={catalog.risks.source} target="_blank" rel="noreferrer">
                Источник
              </a>
            </p>
          )}
        </section>
      ) : null}
      <section className="method-section">
        <h2>Как сопоставляется опрос</h2>
        <p>
          Средняя абсолютная ошибка взвешивается по числу живых ответов. Ранги
          симуляции приводятся к составу опроса. При отсутствии разброса
          корреляция не определена; совпадение лидера требует двух и более
          вариантов и единственного победителя.
        </p>
        <p>
          Проверяйте одинаковые тексты и сопоставимые аудитории. Не подбирайте
          настройки на той же выборке, которой затем подтверждаете качество.
        </p>
      </section>
      <section className="method-section">
        <h2>Следующий этап</h2>
        <p>
          Интервью с продуктовыми командами, калибровка долей и атрибутов на
          источниках из раздела выше, независимый опрос и ретро-тест прошлых
          запусков. Корпоративный SSO, сетевое on-prem-развёртывание и
          тестирование экранов остаются отдельными этапами.
        </p>
      </section>
    </>
  );
}
